export async function getSettings() {
  const { settings } = await chrome.storage.local.get("settings");
  const saved = settings || {};
  return { ...DEFAULTS, ...saved, github: { ...DEFAULTS.github, ...(saved.github || {}) } };
}

export async function saveSettings(patch) {
  const current = await getSettings();
  const next = { ...current, ...patch, github: { ...current.github, ...(patch.github || {}) } };
  await chrome.storage.local.set({ settings: next });
  return next;
}

export async function getStats() {
  const { stats } = await chrome.storage.local.get("stats");
  return stats || { videosScanned: 0, videosHidden: 0, syncs: 0, lastSync: null, notifications: 0 };
}

export async function incrementStats(patch) {
  const s = await getStats();
  for (const [k, v] of Object.entries(patch)) s[k] = typeof v === "number" ? (s[k] || 0) + v : v;
  await chrome.storage.local.set({ stats: s });
  return s;
}
